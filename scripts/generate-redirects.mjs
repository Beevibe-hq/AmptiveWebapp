/**
 * Writes dist/_redirects at build time.
 *
 * These rules have to differ between staging and production — the API proxy points at a
 * different backend, and the vanity tip domains have different hostnames. Netlify's docs
 * are explicit that netlify.toml can't do that:
 *
 *   "Redirects and headers are GLOBAL for all builds – they do not get scoped to contexts
 *    no matter where you define them in the file. For context-specific rules, use
 *    `_headers` or `_redirects` files, which are PER-DEPLOY."
 *
 * So every redirect lives here instead of netlify.toml, generated from environment
 * variables set per Netlify site.
 *
 * Environment variables:
 *   API_ORIGIN   Backend origin to proxy /api/* to.
 *                e.g. https://api.getamptive.com  |  https://amptive-staging.getamptive.com
 *   TIP_DOMAINS  Comma-separated hostnames serving support pages at a bare slug.
 *                e.g. giftmywork.getamptive.com,tipmybusiness.getamptive.com
 *                Optional — omit it and only the /support/:id path form is handled.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, 'dist/_redirects');

const API_ORIGIN = (process.env.API_ORIGIN || '').trim().replace(/\/+$/, '');
const TIP_DOMAINS = (process.env.TIP_DOMAINS || '')
  .split(',')
  .map((d) => d.trim().replace(/^https?:\/\//, '').replace(/\/+$/, ''))
  .filter(Boolean);

if (!API_ORIGIN) {
  // Failing loudly beats shipping a site whose API calls 404, or one that silently
  // proxies production traffic to staging.
  console.error(
    '\n[generate-redirects] API_ORIGIN is not set.\n' +
      '  Set it on the Netlify site (Site configuration → Environment variables), e.g.\n' +
      '    production  API_ORIGIN=https://api.getamptive.com\n' +
      '    staging     API_ORIGIN=https://amptive-staging.getamptive.com\n'
  );
  process.exit(1);
}

const lines = [
  '# Generated by scripts/generate-redirects.mjs — do not edit by hand.',
  `# API_ORIGIN=${API_ORIGIN}`,
  `# TIP_DOMAINS=${TIP_DOMAINS.join(',') || '(none)'}`,
  '',
  '# API proxy. Keeps browser calls same-origin, so CORS never applies — the production',
  '# backend only allows the getamptive.com origin, and calling it directly would break',
  '# the tip domains.',
  `/api/*  ${API_ORIGIN}/api/:splat  200!`,
  '',
  '# Crawler-facing meta tags. The SPA shell has none, so these routes render through the',
  '# SEO function, which returns the untouched shell to real browsers.',
  '/events/:id  /.netlify/functions/seo-renderer  200!',
  '/blog/:id    /.netlify/functions/seo-renderer  200!',
  '/support/:id /.netlify/functions/seo-renderer  200!',
];

if (TIP_DOMAINS.length) {
  lines.push(
    '',
    '# Support links are shared as a bare slug on the tip domains (giftmywork…/joseph),',
    '# which never matches /support/:id above. No `!` here on purpose: real files must win,',
    '# or the SEO function\'s own fetch of /index.html would be rewritten into itself and recurse.'
  );
  for (const host of TIP_DOMAINS) {
    lines.push(`https://${host}/:slug  /.netlify/functions/seo-renderer  200`);
  }
}

lines.push(
  '',
  '# SPA fallback — must stay last.',
  '/*  /index.html  200',
  ''
);

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join('\n'));

console.log(`[generate-redirects] wrote dist/_redirects`);
console.log(`[generate-redirects]   API_ORIGIN  ${API_ORIGIN}`);
console.log(`[generate-redirects]   TIP_DOMAINS ${TIP_DOMAINS.join(', ') || '(none)'}`);
